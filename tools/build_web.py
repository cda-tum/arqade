"""Build the games for the browser with pygbag, and bundle them for a release.

    uv run --project tools tools/build_web.py                  every game with a game.json
    uv run --project tools tools/build_web.py quantum-pong     just these
    uv run --project tools tools/build_web.py --serve quantum-pong
                                                               one game on pygbag's test server
    ... --version 1.2.0                                        name the release (default: dev)

pygbag packages one folder whose main.py starts the game. A game's code lives
in <game>/src/<package>/ and the shared code in common/src/arqade_common/,
so each game is first staged in build/stage/<game-id>/ (git-ignored):

    main.py            starts the game: asyncio.run(main([]))
    <package>/         the game's package
    arqade_common/     the shared package

and pygbag builds that. The release bundle, build/arqade-games-<version>.zip,
has one folder per game: pygbag's output (index.html and the .apk with the
game), game.json (with "version" from the game's pyproject.toml) and
thumbnail.png (made from batocera/logos/<package>-wide.png).
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tomllib
import urllib.request
import zipfile
from pathlib import Path

os.environ.setdefault("PYGAME_HIDE_SUPPORT_PROMPT", "1")
import pygame  # noqa: E402

REPO = Path(__file__).resolve().parent.parent
BUILD = REPO / "build"
COMMON = REPO / "common" / "src" / "arqade_common"
LOGOS = REPO / "batocera" / "logos"

THUMBNAIL_SIZE = (640, 360)  # 16:9, what the website's game cards show

PYGBAG_ARGS = [
    # Let the embedding page's "click to start" be the user gesture that
    # unlocks audio, instead of pygbag showing a second click-to-start.
    "--ume_block", "0",
    # Otherwise pygbag asks "Are you sure you want to navigate away?" every
    # time the page is left (the site's back link, quitting, the back button).
    "--can_close", "1",
]


def find_games(ids: list[str]) -> list[Path]:
    """Game folders to build: those named, else every one with a game.json."""
    if ids:
        missing = [i for i in ids if not (REPO / i / "game.json").is_file()]
        if missing:
            sys.exit(f"no game.json in: {', '.join(missing)}")
        return [REPO / i for i in ids]
    return sorted(p.parent for p in REPO.glob("*/game.json"))


def package_name(game_dir: Path) -> str:
    return game_dir.name.replace("-", "_")


def manifest(game_dir: Path) -> dict:
    """game.json, plus the version from pyproject.toml (kept in one place)."""
    data = json.loads((game_dir / "game.json").read_text())
    if data["id"] != game_dir.name:
        sys.exit(f"{game_dir.name}/game.json: id must be the folder name, not {data['id']!r}")
    with open(game_dir / "pyproject.toml", "rb") as f:
        data["version"] = tomllib.load(f)["project"]["version"]
    return data


def stage(game_dir: Path) -> Path:
    """Copy one game and the shared code into build/stage/<id>/ for pygbag."""
    package = package_name(game_dir)
    out = BUILD / "stage" / game_dir.name
    shutil.rmtree(out, ignore_errors=True)
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc", "py.typed", "*_test.py")
    shutil.copytree(game_dir / "src" / package, out / package, ignore=ignore)
    shutil.copytree(COMMON, out / "arqade_common", ignore=ignore)
    # pygbag reads main.py's own imports to decide which runtime modules to
    # load (pygame-ce among them) and looks for asyncio.run(main()), so both
    # are spelled out here rather than left to the game's package.
    (out / "main.py").write_text(
        f'"""Web entry point, generated by tools/build_web.py."""\n'
        f"import asyncio\n\n"
        f"import pygame  # noqa: F401 -- tells pygbag to load pygame-ce\n\n"
        f"from {package}.main import main\n\n"
        f"asyncio.run(main([]))\n"
    )
    return out


def pygbag(staged: Path, title: str, *, serve: bool) -> None:
    cmd = [sys.executable, "-m", "pygbag", *PYGBAG_ARGS, "--title", title]
    if serve:
        subprocess.run([*cmd, str(staged)], check=True)
        return
    # pygbag downloads its page template without a timeout, so a dropped
    # connection hangs it forever: give each build 10 minutes and one retry.
    for attempt in (1, 2):
        try:
            subprocess.run([*cmd, "--build", str(staged)], check=True, timeout=600)
            return
        except subprocess.TimeoutExpired:
            print(f"   pygbag timed out (attempt {attempt} of 2)")
    sys.exit(f"pygbag kept timing out on {staged.name}")


def make_thumbnail(game_dir: Path, target: Path) -> None:
    """The game's wide logo, letterboxed onto 16:9 in its own background colour.
    Scaled by whole-pixel steps (nearest neighbour) so the pixel art stays crisp."""
    logo = pygame.image.load(LOGOS / f"{package_name(game_dir)}-wide.png")
    width, height = THUMBNAIL_SIZE
    scale = min(width / logo.get_width(), height / logo.get_height())
    scaled = pygame.transform.scale(logo, (round(logo.get_width() * scale), round(logo.get_height() * scale)))
    canvas = pygame.Surface(THUMBNAIL_SIZE)
    canvas.fill(logo.get_at((0, 0)))
    canvas.blit(scaled, scaled.get_rect(center=(width // 2, height // 2)))
    pygame.image.save(canvas, str(target))


def accept_any_tar(index_html: Path) -> None:
    """Let pygbag's loader open the game's .tar.gz whether or not the browser
    has already unpacked it. Many web servers (Vite's, Apache with the common
    `AddEncoding x-gzip .gz`) send .gz files with "Content-Encoding: gzip",
    so the browser gunzips the download and the loader, which insists on
    gzip, gets a plain tar it refuses."""
    html = index_html.read_text()
    strict = 'tarfile.open(fileobj=archive, mode="r:gz")'
    if strict not in html:
        sys.exit(f"{index_html}: pygbag's loader changed, check accept_any_tar()")
    index_html.write_text(html.replace(strict, 'tarfile.open(fileobj=archive, mode="r:*")'))


# Replaces pygbag's own canvas sizing, which stretches the game to any size
# (2.1x, say): pixels then come out 2 or 3 screen pixels wide, unevenly, and
# pixel art looks ragged. This scales by whole device pixels instead, like
# the cabinet's 1080p panel does, and falls back to a plain fit only when
# the window is smaller than the game.
_WHOLE_PIXEL_SCALING = """
<script>
// Added by tools/build_web.py: scale the game by whole pixels (see there).
(() => {
  const fit = () => {
    const canvas = document.getElementById("canvas");
    if (!canvas || !canvas.width || !canvas.height) return;
    const dpr = window.devicePixelRatio || 1;
    const room = Math.min(innerWidth * dpr / canvas.width, innerHeight * dpr / canvas.height);
    const scale = room >= 1 ? Math.floor(room) : room;
    const width = `${canvas.width * scale / dpr}px`, height = `${canvas.height * scale / dpr}px`;
    if (canvas.style.width === width && canvas.style.height === height) return;
    Object.assign(canvas.style, { position: "absolute", inset: "0", margin: "auto",
                                  width, height, imageRendering: "pixelated" });
  };
  addEventListener("resize", fit);
  // The game sets the canvas's own size when it opens its display, and SDL
  // may reset the style: refit whenever either changes.
  addEventListener("DOMContentLoaded", () => {
    const canvas = document.getElementById("canvas");
    if (canvas) new MutationObserver(fit).observe(canvas, { attributes: true, attributeFilter: ["width", "height", "style"] });
    fit();
  });
})();
</script>
"""


def scale_by_whole_pixels(index_html: Path) -> None:
    html = index_html.read_text()
    managed = "user_canvas_managed : 0,"
    if managed not in html or "</body>" not in html:
        sys.exit(f"{index_html}: pygbag's template changed, check scale_by_whole_pixels()")
    # 1 tells pygbag the page sizes the canvas itself.
    html = html.replace(managed, "user_canvas_managed : 1,")
    index_html.write_text(html.replace("</body>", _WHOLE_PIXEL_SCALING + "</body>", 1))


# --- Self-hosted runtime. By default pygbag pages load Python, pygame-ce and
# a few helpers from pygame-web.github.io: every player's browser contacts
# GitHub, and the games stop working if those files move. The bundle instead
# carries them once, in _runtime/ next to the game folders (same paths as on
# pygame-web.github.io), and each game page sends those requests there.
PYGBAG_HOST = "https://pygame-web.github.io/"
RUNTIME_DIR = "_runtime"

# Every runtime file the games load, as a path on PYGBAG_HOST, for the pinned
# pygbag version. Found by playing each game with the runtime served through a
# recording proxy; a file missing here shows up as a 404 in the browser.
RUNTIME_FILES = [
    "cdn/0.9.3/pythons.js",
    "cdn/0.9.3/empty.html",
    "cdn/0.9.3/cpythonrc.py",
    "cdn/0.9.3/cpython312/main.js",
    "cdn/0.9.3/cpython312/main.wasm",
    "cdn/0.9.3/cpython312/main.data",
    "cdn/index-0.9.3-cp312.json",
    "cdn/cp312/pygame_ce-2.5.7-cp312-cp312-wasm32_bi_emscripten.whl",
    "cdn/vtx.js",
    "cdn/vt/xterm.js",
    "cdn/vt/xterm.css",
    "cdn/vt/xterm-addon-image.js",
]

_RUNTIME_REDIRECT = """<script>
// Added by tools/build_web.py: load pygbag's runtime from this bundle's
// _runtime/ folder instead of pygame-web.github.io (see there).
(() => {
  const upstream = "%(host)s";
  const local = new URL("../%(dir)s/", location.href).href;
  const map = (url) => {
    const u = new URL(url, location.href);
    if (u.href.startsWith(upstream)) return local + u.href.slice(upstream.length);
    // On any localhost page pygbag assumes its own test server
    // (localhost:8000) and asks it for packages under /cdn/; those are in
    // _runtime/cdn/ too.
    const localhost = ["localhost", "127.0.0.1"].includes(u.hostname);
    if ((localhost || u.origin === location.origin) && u.pathname.startsWith("/cdn/")) return local + u.pathname.slice(1);
    return url;
  };
  const fetch0 = window.fetch;
  window.fetch = (input, init) =>
    fetch0(input instanceof Request ? new Request(map(input.url), input) : map(String(input)), init);
  const open0 = XMLHttpRequest.prototype.open;
  XMLHttpRequest.prototype.open = function (method, url, ...rest) {
    return open0.call(this, method, map(String(url)), ...rest);
  };
})();
</script>
""" % {"host": PYGBAG_HOST, "dir": RUNTIME_DIR}


def use_bundled_runtime(index_html: Path) -> None:
    """Point the page's own references at ../_runtime/ and add the redirect
    for the requests pygbag makes later (package index, wheels)."""
    html = index_html.read_text()
    config_cdn = re.compile(r'cdn : "' + re.escape(PYGBAG_HOST) + r'([^"]*)",')
    if not config_cdn.search(html) or not html.startswith("<html"):
        sys.exit(f"{index_html}: pygbag's template changed, check use_bundled_runtime()")
    # pygbag's config.cdn must be absolute: some of its scripts resolve it
    # relative to their own location, which doubles a relative path.
    html = config_cdn.sub(
        lambda m: f'cdn : new URL("../{RUNTIME_DIR}/{m[1]}", location.href).href,', html
    )
    # The rest (script and iframe sources) are resolved by the page itself.
    html = html.replace(PYGBAG_HOST, f"../{RUNTIME_DIR}/")
    index_html.write_text(_RUNTIME_REDIRECT + html)


def mirror_runtime(bundle: Path) -> None:
    """Download RUNTIME_FILES into bundle/_runtime/ (cached in build/runtime-cache)."""
    cache = BUILD / "runtime-cache"
    for rel in RUNTIME_FILES:
        cached = cache / rel
        if not cached.exists():
            cached.parent.mkdir(parents=True, exist_ok=True)
            print(f"   runtime: {rel}")
            urllib.request.urlretrieve(PYGBAG_HOST + rel, cached)
        target = bundle / RUNTIME_DIR / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(cached, target)


def assemble(game_dir: Path, staged: Path, bundle: Path) -> None:
    """build/bundle/<id>/: pygbag's output, game.json and thumbnail.png."""
    out = bundle / game_dir.name
    shutil.rmtree(out, ignore_errors=True)
    shutil.copytree(staged / "build" / "web", out)
    accept_any_tar(out / "index.html")
    scale_by_whole_pixels(out / "index.html")
    use_bundled_runtime(out / "index.html")
    (out / "game.json").write_text(json.dumps(manifest(game_dir), indent=2) + "\n")
    make_thumbnail(game_dir, out / "thumbnail.png")


def zip_bundle(bundle: Path, version: str) -> Path:
    target = BUILD / f"arqade-games-{version}.zip"
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in sorted(bundle.rglob("*")):
            if path.is_file():
                zf.write(path, path.relative_to(bundle).as_posix())
    return target


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("games", nargs="*", help="game folders (default: all with a game.json)")
    parser.add_argument("--version", default="dev", help="release version, for the zip's name")
    parser.add_argument("--serve", action="store_true", help="run one game on pygbag's test server")
    args = parser.parse_args()

    games = find_games(args.games)
    if args.serve:
        if len(games) != 1:
            sys.exit("--serve takes exactly one game")
        pygbag(stage(games[0]), manifest(games[0])["title"], serve=True)
        return

    bundle = BUILD / "bundle"
    shutil.rmtree(bundle, ignore_errors=True)
    for game_dir in games:
        print(f"== {game_dir.name}")
        staged = stage(game_dir)
        pygbag(staged, manifest(game_dir)["title"], serve=False)
        assemble(game_dir, staged, bundle)
    mirror_runtime(bundle)
    print(f"-> {zip_bundle(bundle, args.version).relative_to(REPO)}")


if __name__ == "__main__":
    main()
